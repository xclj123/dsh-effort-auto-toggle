// 0.2.0 model-adaptive ladders: the host `llm` service (dsh-llm) exposes
// resolveModelInfo(provider, model) -> { reasoning: { efforts: [{id}, ...] } },
// i.e. the EXACT effort levels of the target model. We keep one resolved
// ladder per provider|model (capabilities are stable for a process life).
let llmRef = null;
const ladderCache = new Map();
async function effortLadderFor(provider, model) {
    if (typeof provider !== 'string' || provider === '' || typeof model !== 'string' || model === '')
        return DEFAULT_LADDER.slice();
    const key = provider + '|' + model;
    const hit = ladderCache.get(key);
    if (Array.isArray(hit))
        return hit;
    if (llmRef === null || typeof llmRef.resolveModelInfo !== 'function')
        return DEFAULT_LADDER.slice();
    try {
        const info = await llmRef.resolveModelInfo(provider, model);
        const ladder = buildLadder(info && info.reasoning && info.reasoning.efforts);
        ladderCache.set(key, ladder);
        return ladder;
    }
    catch {
        return DEFAULT_LADDER.slice(); // not cached: retried on the next request
    }
}

/** Unwrap a schemastery volatile container ({ get() }) to its plain value. */
function plainValue(v) {
    if (v !== null && typeof v === 'object' && typeof v.get === 'function' && Object.keys(v).length <= 1) {
        try { return plainValue(v.get()); } catch { return undefined; }
    }
    return v;
}

/** Resolve the composition config with volatile containers unwrapped. */
function resolvePlainConfig(config) {
    const out = {};
    for (const [k, v] of Object.entries(config ?? {})) {
        const pv = plainValue(v);
        out[k] = pv === undefined ? (DEFAULT_CONFIG[k] ?? pv) : pv;
    }
    return out;
}

/**
 * 0.2.x host: the settings service exposes describe()/update() keyed by
 * profile entry id (there is no register()). Bind lazily — the service may
 * become available after apply().
 */
function bindSettingsForms(ctx) {
    let forms = null;
    try {
        ctx.inject(['llm'], (lctx) => {
            const svc = lctx && lctx.llm;
            if (svc && typeof svc.resolveModelInfo === 'function')
                llmRef = svc;
        });
    }
    catch { /* no llm service: DEFAULT_LADDER semantics apply */ }
    ctx.inject(['settings'], (sctx) => {
        const svc = sctx && sctx.settings;
        if (svc && typeof svc.describe === 'function' && typeof svc.update === 'function') forms = svc;
    });
    return () => forms;
}

/** The settings namespace actually served for this plugin (entry id first, package name fallback). */
function settingsEntryNs(ctx, rows) {
    const candidates = [];
    try {
        const entry = ctx && ctx.fiber ? ctx.fiber.entry : null;
        const raw = entry ? (entry.options && entry.options.id) || entry.id : null;
        if (typeof raw === 'string' && raw !== '') {
            const colon = raw.lastIndexOf(':');
            candidates.push(colon === -1 ? raw : raw.slice(colon + 1));
        }
    } catch {}
    candidates.push(PKG_NS);
    if (!Array.isArray(rows)) return candidates[candidates.length - 1];
    for (const c of candidates) if (rows.some((r) => r && r.ns === c)) return c;
    return candidates[candidates.length - 1];
}

/**
 * Live config accessor: reads the plugin's volatile form value (what the
 * settings document actually says now) over the composition defaults, so a
 * toggle flip from the client is picked up on the very next request without
 * a reload. Falls back to the composition config when the service is absent.
 */
function makeLiveCfg(ctx, getForms, baseConfig) {
    return () => {
        const forms = getForms();
        if (!forms) return baseConfig;
        try {
            const rows = forms.describe();
            if (!Array.isArray(rows)) return baseConfig;
            const ns = settingsEntryNs(ctx, rows);
            const row = rows.find((r) => r && r.ns === ns);
            if (row && row.value && typeof row.value === 'object') {
                return { ...baseConfig, ...row.value };
            }
        } catch {}
        return baseConfig;
    };
}

// ===== 0.3.0 adaptive signals: retry / context-length / difficulty + stats =====
const sessionSignals = new Map();
const STATS_FALLBACK_MAX_OUT = 600;
const STATS_WRITE_MIN_INTERVAL_MS = 30 * 60 * 1000;
// Continuity ("this session is mid-work, do not drop to low"). The SIZE policy
// lives in scheduler.js (`rungsForArgs`): a bare `ls` buys no rung, 800 chars
// buys one, 3200 buys two. What lives here is only the TIME window — evidence
// that a session is mid-work decays, so a tool call from 40 minutes ago must
// not lift anything. Keeping the two halves in one place stops the double
// count that a separate continuity lift next to a tool upgrade used to cause.
const CONTINUITY_WINDOW_MS = 10 * 60 * 1000;
function toolResultText(data) {
    const m = data && data.message;
    const c = m && Array.isArray(m.content) ? m.content : [];
    let t = "";
    for (const p of c) {
        if (p && typeof p === "object" && typeof p.text === "string") t += p.text + "\n";
    }
    return t;
}
const TOOL_FAIL_PATTERNS = ["[EXIT_CODE", "[timed out after ", "[TIMEOUT", "[COMMAND_FAILED", "Traceback (most recent call last)", "[error: sandbox"];
function isToolFailureText(t) {
    const scan = t.slice(0, 2400) + "\n" + t.slice(-400);
    for (const p of TOOL_FAIL_PATTERNS) if (scan.includes(p)) return true;
    const m = scan.match(/\[exit code:\s*(\d+)\]/g);
    if (m) {
        for (const one of m) {
            const n = parseInt(one.replace(/\D+/g, ""), 10);
            if (n !== 0) return true;
        }
    }
    return false;
}

function signalsOf(sessionId) {
    const key = typeof sessionId === "string" && sessionId ? sessionId : "default";
    let sig = sessionSignals.get(key);
    if (sig === undefined) {
        sig = {
            lastUserText: null,
            lastUserAt: 0,
            curTurn: -1,
            curTurnSteps: 0,
            lastTurnSteps: 0,
            lastInputTokens: 0,
            seenUsage: new Set(),
            steps: 0,
            outTokens: 0,
            tierOut: new Map(),
            tierSteps: new Map(),
            statsWrittenAt: 0, toolFails: [], successStreak: 0, lastSettledTurn: -1,
            statsDirtySteps: 0,
        };
        sessionSignals.set(key, sig);
    }
    return sig;
}
// Retry + long-context + hard-turn boosts. Applied AFTER the classifier
// verdict, BEFORE scheduleEffort, on both the modern claim path and the
// legacy agent/request path. Returns the (possibly) bumped tier and appends
// tags to the source string.
function settleStreak(sessionId, turn) {
    const sig = signalsOf(sessionId);
    if (typeof turn === "number" && sig.lastSettledTurn === turn) return;
    const doneSteps = sig.curTurnSteps > 0 ? sig.curTurnSteps : sig.lastTurnSteps;
    if (doneSteps <= 0) return;
    const recentFail = sig.toolFails.some((t) => Date.now() - t < 600000);
    if (!recentFail && doneSteps <= 6) sig.successStreak = (sig.successStreak || 0) + 1;
    else sig.successStreak = 0;
    if (typeof turn === "number") sig.lastSettledTurn = turn;
}

function applySignalBoosts(sessionId, text, tier, source, isFresh) {
    const sig = signalsOf(sessionId);
    const now = Date.now();
    const tags = [];
    let out = tier;
    const failCount = sig.toolFails.filter((t) => now - t < 600000).length;
    if (failCount >= 2 && out === "low") {
        out = "high";
        tags.push("fail");
    }
    if (tags.length === 0 && out === "high" && (sig.successStreak || 0) >= 2 && String(source).indexOf("minimax") !== 0) {
        out = "low";
        tags.push("calm");
    }
    if (tags.length > 0)
        source = source + "+" + tags.join("+");
    return { tier: out, source };
}

// Ingest one usage record: turn bookkeeping, context length, and the
// savings accumulator behind the tooltip stats.
function ingestUsageSignal(sessionId, turn, step, inputTokens, outputTokens, tier) {
    const sig = signalsOf(sessionId);
    const key = String(turn) + ":" + String(step);
    if (sig.seenUsage.has(key))
        return;
    sig.seenUsage.add(key);
    if (sig.seenUsage.size > 512)
        sig.seenUsage.clear();
    if (typeof turn === "number" && turn !== sig.curTurn) {
        if (sig.curTurn !== -1)
            sig.lastTurnSteps = sig.curTurnSteps;
        sig.curTurn = turn;
        sig.curTurnSteps = 0;
    }
    sig.curTurnSteps += 1;
    sig.lastInputTokens = typeof inputTokens === "number" ? inputTokens : sig.lastInputTokens;
    if (typeof outputTokens !== "number" || outputTokens <= 0)
        return;
    sig.steps += 1;
    sig.outTokens += outputTokens;
    sig.statsDirtySteps += 1;
    if (typeof tier === "string" && tier) {
        sig.tierOut.set(tier, (sig.tierOut.get(tier) ?? 0) + outputTokens);
        sig.tierSteps.set(tier, (sig.tierSteps.get(tier) ?? 0) + 1);
    }
}
export function statsSummaryOf(sig) {
    if (!sig || sig.steps < 3)
        return "";
    const maxSteps = sig.tierSteps.get("max") ?? 0;
    const maxAvg = maxSteps > 0 ? Math.round(sig.tierOut.get("max") / maxSteps) : STATS_FALLBACK_MAX_OUT;
    const estAlwaysMax = maxAvg * sig.steps;
    if (estAlwaysMax <= 0)
        return "";
    const saved = Math.max(0, Math.min(90, Math.round(100 * (1 - sig.outTokens / estAlwaysMax))));
    if (saved <= 0)
        return "";
    return "saved ~" + saved + "% output tokens vs always-max (" + sig.steps + " steps)";
}

export function apply(ctx, config = DEFAULT_CONFIG) {
    sessionSignals.clear();
    const baseConfig = resolvePlainConfig(config);
    const getForms = bindSettingsForms(ctx);
    const liveCfg = makeLiveCfg(ctx, getForms, baseConfig);
    const scoreCache = new TurnScoreCache(64);
    const scorerBackoff = new ScorerBackoff(60 * 1000);
    const ledger = new Ledger(config.ledgerDir || defaultLedgerDir());
    overrideStateDir = config.ledgerDir || defaultLedgerDir();
    const pending = new Map();
    const scannedIndex = new Map();
    const on = ctx.on;
    // host 0.2.1-rc.3: agent/request payload only carries {turn,step,signal};
    // read the last claimed user message and usage from broadcast events.
    let lastClaimedText = null;
    let lastClaimedTurn = -1;
    const recentUsage = [];
    const recentToolCallsCache = [];
    // 0.3.4: ledger rows are written straight off the session's own event
    // stream (session/event) instead of being harvested inside agent/request.
    // agent/request is @deprecated upstream, so nothing that can be done on a
    // live event may depend on it any more. `ledgerWritten` keeps the two
    // paths idempotent: whichever sees a turn:step first writes it, the other
    // becomes a no-op catch-up.
    const ledgerWritten = new Set();
    // Last wire effort actually handed to the provider for this session. Used
    // only as attribution fallback when a usage row arrives with no matching
    // plan (plugin enabled mid-session, session restored from disk).
    const lastWireBySession = new Map();
    // The host echoes our injected effort back as the next seed.reasoningEffort.
    // Track our own overrides (persisted) plus genuine manual picks so an echo
    // is never mistaken for a manual selection. Also remembers the manual effort
    // that was live BEFORE auto was armed, to restore it right after disarming.
    let lastOverride = loadOverrideState();
    // 0.2.3: last decision taken at claim time (host 0.2.2+ path), kept for
    // first-step ledger attribution in the read-only agent/request hook.
    let claimedDecision = null;
    // 0.3.0: push the savings snapshot into the settings form (tooltip data
    // source). Throttled: a settings write re-materializes the fiber, so at
    // most once per 30min or per 50 fresh steps. Fire-and-forget.
    let statsPushInFlight = false;
    /**
     * Write one usage row to the ledger. Idempotent per session:turn:step.
     *
     * This used to live entirely inside the agent/request hook, which is the
     * one hook the host has deprecated — so on a host that stops firing it the
     * ledger would go silent. It is now called from the session/event handler
     * the instant the provider reports usage, and agent/request only sweeps up
     * whatever a live event did not cover.
     *
     * @param sessionId  owning session
     * @param usage      { turn, step, provider, model, inputTokens, outputTokens,
     *                     cacheReadTokens, cacheWriteTokens }
     * @param fallbackReason  attribution text used when no plan was recorded
     */
    function recordUsage(sessionId, usage, fallbackReason) {
        const key = `${usage.turn}:${usage.step}`;
        const dedupe = `${sessionId}|${key}`;
        if (ledgerWritten.has(dedupe))
            return;
        ledgerWritten.add(dedupe);
        if (ledgerWritten.size > 2048)
            ledgerWritten.clear();
        const decision = pending.get(key);
        if (decision !== undefined)
            pending.delete(key);
        const ladder = ladderCache.get(`${usage.provider}|${usage.model}`) ?? DEFAULT_LADDER;
        const wire = lastWireBySession.get(sessionId);
        const record = {
            ts: new Date().toISOString(),
            sessionId,
            turn: usage.turn,
            step: usage.step,
            model: usage.model,
            provider: usage.provider,
            tier: decision?.tier ?? guessSemantic(wire, ladder),
            effort: decision?.effort ?? (typeof wire === 'string' && wire !== '' ? wire : semanticToLadder('high', ladder)),
            reason: decision?.reason ?? fallbackReason,
            classifierSource: decision?.classifierSource ?? 'unknown',
            classifierScore: decision?.classifierScore ?? 0,
            inputTokens: usage.inputTokens,
            outputTokens: usage.outputTokens,
            cacheReadTokens: typeof usage.cacheReadTokens === 'number' ? usage.cacheReadTokens : 0,
            cacheWriteTokens: typeof usage.cacheWriteTokens === 'number' ? usage.cacheWriteTokens : 0,
        };
        void ledger.append(record);
        ingestUsageSignal(sessionId, usage.turn, usage.step, usage.inputTokens, usage.outputTokens, record.tier);
        pushStatsSnapshot(false);
    }
    function pushStatsSnapshot(force) {
        const now = Date.now();
        let dirtiest = null;
        let dirtySteps = 0;
        for (const [sid, sig] of sessionSignals) {
            if (sig.statsDirtySteps > dirtySteps) { dirtySteps = sig.statsDirtySteps; dirtiest = sig; }
        }
        if (dirtiest === null) return;
        if (!force && now - dirtiest.statsWrittenAt < STATS_WRITE_MIN_INTERVAL_MS && dirtiest.statsDirtySteps < 50) return;
        const summary = statsSummaryOf(dirtiest);
        if (!summary || statsPushInFlight) return;
        dirtiest.statsWrittenAt = now;
        dirtiest.statsDirtySteps = 0;
        const cfg0 = liveCfg();
        if (cfg0.statsSummary === summary) return;
        const forms0 = getForms();
        const svc = forms0 && typeof forms0.update === 'function' ? forms0 : null;
        if (!svc) return;
        statsPushInFlight = true;
        Promise.resolve().then(async () => {
            const rows = await svc.describe();
            const ns = settingsEntryNs(ctx, rows);
            const row = rows.find((r) => r.ns === ns);
            if (!row) return;
            await svc.update(ns, { statsSummary: summary }, row.revision);
        }).then(() => { statsPushInFlight = false; }).catch(() => { statsPushInFlight = false; });
    }
    function recentCallsFor(sessionId) {
        const now = Date.now();
        const same = recentToolCallsCache.filter((c) => c.sessionId === null || c.sessionId === sessionId);
        const lastAt = same.reduce((max, c) => Math.max(max, c.at), 0);
        const fresh = same.filter((c) => now - c.at < CONTINUITY_WINDOW_MS);
        const calls = fresh.slice(-8).map((c) => ({ name: c.name, argsSize: c.argsSize }));
        return { same, lastAt, fresh, calls };
    }
    // Claim-time decision for hosts where effort rides the model selection
    // (agent.model.select) instead of the agent/request waterfall. Must stay
    // synchronous: it runs inside the claim broadcast, before the step's
    // selection is read, so the first step of the turn already runs at the
    // scheduled tier.
    function modernClaimDecision(rec) {
        const agent = rec && rec.agent;
        if (!hostModern(agent))
            return;
        const cfg = liveCfg();
        if (!cfg.enabled)
            return;
        const text = messageText(rec && rec.message);
        if (typeof text !== "string" || text.trim().length === 0)
            return;
        const sel = agent.model.current();
        if (!sel || typeof sel.provider !== "string" || !sel.provider || typeof sel.model !== "string" || !sel.model)
            return;
        const cacheKey = sel.provider + "|" + sel.model;
        if (cfg.autoOn !== true) {
            // Disarmed: only clamp a manual `off` on forced-thinking models,
            // and only when the ladder is already cached (staying synchronous).
            if (sel.reasoningEffort === "off" && cfg.clampForcedThinkingOff === true) {
                const ladder0 = ladderCache.get(cacheKey);
                if (ladder0 !== undefined) {
                    const clamp = clampForModel("off", sel.model, ladder0);
                    if (clamp.clamped)
                        modernSelect(agent, clamp.effort);
                }
            }
            return;
        }
        const ladder = ladderCache.get(cacheKey) ?? DEFAULT_LADDER;
        let result = scoreCache.lookup(text);
        if (result === undefined) {
            result = heuristicClassify(text);
            // Skip the scorer entirely while it is cooling down after a failure:
            // the heuristic verdict below still stands, we just refuse to pay the
            // timeout again for the same message on the very next step.
            if (cfg.mode === "minimax" && !scorerBackoff.cooling(text)) {
                // Fire-and-forget refine: the verdict lands in the score cache
                // and is applied by the next decision point (same message
                // re-claimed, or the read-only request hook of the next step).
                const text0 = text;
                void minimaxClassify(text0, {
                    apiKey: cfg.minimaxApiKey,
                    baseUrl: cfg.minimaxBaseUrl,
                    model: cfg.minimaxModel,
                    timeoutMs: cfg.scoreTimeoutMs,
                }).then((r) => {
                    if (r && r.note === undefined)
                        scoreCache.remember(text0, r);
                    else
                        scorerBackoff.markFailed(text0);
                }).catch(() => { scorerBackoff.markFailed(text0); });
            }
        }
        const sessionId = sessionIdOf(agent);
        let tier = result && typeof result.tier === "string" ? result.tier : "high";
        let source = result && typeof result.source === "string" ? result.source : "unknown";
        // Tool-load escalation is NOT applied here: the scheduler owns it, off
        // the same window-filtered calls, one time. Lifting here as well used to
        // double count (low -> continuity high -> one tool rung -> max), which is
        // how a score-20 conversation reached max on its own.
        settleStreak(sessionId, typeof rec.turn === "number" ? rec.turn : undefined);
        const boosted = applySignalBoosts(sessionId, text, tier, source, true);
        tier = boosted.tier;
        source = boosted.source;
const decision = scheduleEffort({
            scoredTier: tier,
            recentCalls: recentCallsFor(sessionId).calls,
            allowToolUpgrade: cfg.allowToolUpgrade,
            selected: "auto",
            defaultTier: "high",
        });
        const effort = decision.manual ? decision.effort : semanticToLadder(decision.effort, ladder);
        if (!decision.manual)
            assertScheduledEffort(effort, ladder, "dsh-effort-auto-toggle claimed-select");
        claimedDecision = {
            turn: typeof rec.turn === "number" ? rec.turn : -1,
            tier,
            effort,
            reason: decision.reason,
            classifierSource: source,
            classifierScore: result && typeof result.score === "number" ? result.score : 0,
        };
        if (effort !== sel.reasoningEffort)
            modernSelect(agent, effort);
        // 0.3.4: publish the claim decision onto the step the claim applies to.
        // The claim is the turn's first step by definition, and seeding it here
        // is what lets the ledger stay attributed on a host that never calls
        // agent/request at all (that hook is deprecated upstream).
        if (claimedDecision.turn >= 0) {
            const claimKey = `${claimedDecision.turn}:1`;
            pending.set(claimKey, {
                tier: claimedDecision.tier,
                effort,
                reason: claimedDecision.reason,
                classifierSource: claimedDecision.classifierSource,
                classifierScore: claimedDecision.classifierScore,
            });
            if (pending.size > 128) {
                const oldest = pending.keys().next().value;
                if (oldest !== undefined)
                    pending.delete(oldest);
            }
            lastWireBySession.set(sessionId, effort);
        }
        ctx.logger?.info?.("[effort-auto-toggle] claimed: turn=%s tier=%s(%s) -> select %s", String(claimedDecision.turn), tier, source, effort);
    }
    let manualPick = { sessionId: null, effort: undefined };
    on("agent/inbox/claimed", (rec) => {
        try {
            const t = messageText(rec && rec.message);
            if (typeof t === "string" && t.trim().length > 0) {
                lastClaimedText = t;
                lastClaimedTurn = typeof rec.turn === "number" ? rec.turn : -1;
            }
        } catch {}
        try {
            modernClaimDecision(rec);
        } catch {}
    });
    on("session/event", (session, event) => {
        try {
            if (event && event.type === "tool/result" && event.data) {
                const trText = toolResultText(event.data);
                if (trText && isToolFailureText(trText)) {
                    const sig = signalsOf(sessionIdOfEvent(session));
                    sig.toolFails.push(Date.now());
                    if (sig.toolFails.length > 8) sig.toolFails.shift();
                }
            }

            if (event && event.type === "tool/call" && event.data && typeof event.data.name === "string") {
                const a = event.data.arguments;
                const argsSize = typeof a === "string" ? a.length : (()=>{try{return JSON.stringify(a).length}catch{return 0}})();
                recentToolCallsCache.push({ name: event.data.name, argsSize, sessionId: sessionIdOfEvent(session), at: Date.now() });
                if (recentToolCallsCache.length > 32) recentToolCallsCache.shift();
            }
            if (!event || event.type !== "assistant/message" || !event.data) return;
            const usage = event.data.usage;
            if (!usage || typeof usage.inputTokens !== "number" || typeof usage.outputTokens !== "number") return;
            const source = event.data.message && event.data.message.source ? event.data.message.source : {};
            const row = {
                sessionId: sessionIdOfEvent(session),
                turn: typeof event.data.turn === "number" ? event.data.turn : 0,
                step: typeof event.data.step === "number" ? event.data.step : 0,
                provider: typeof source.provider === "string" ? source.provider : "unknown",
                model: typeof source.model === "string" ? source.model : "unknown",
                inputTokens: usage.inputTokens,
                outputTokens: usage.outputTokens,
                cacheReadTokens: typeof usage.cacheReadTokens === "number" ? usage.cacheReadTokens : 0,
                cacheWriteTokens: typeof usage.cacheWriteTokens === "number" ? usage.cacheWriteTokens : 0,
            };
            recentUsage.push(row);
            if (recentUsage.length > 256) recentUsage.shift();
            // Primary write path: the host told us the provider spent tokens, so
            // the row is complete right now. No deprecated hook involved.
            recordUsage(row.sessionId, row, '无记录（插件中途启用或会话恢复）');
        } catch {}
    });
    on('agent/request', async (payload, next) => {
        const seed = await next();
        const cfg = liveCfg();
        const modern = hostModern(payload && payload.agent);
        if (!cfg.enabled)
            return seed;
        const agent = payload.agent;
        const events = readEvents(agent);
        const sessionId = sessionIdOf(agent);
        const provider = typeof seed.provider === 'string' ? seed.provider : '';
        const model = typeof seed.model === 'string' ? seed.model : '';
        const ladder = await effortLadderFor(provider, model);
        // 1) Ledger catch-up. The authoritative write path is the session/event
        //    handler (see recordUsage): it fires when the provider reports
        //    usage, with no deprecated hook in the loop. agent/request only
        //    sweeps whatever a live event did not cover — e.g. rows already in
        //    the log before the plugin was armed, or a host whose event stream
        //    was not wired. recordUsage() dedupes by session:turn:step, so a row
        //    seen here that was already written is a cheap no-op.
        lastWireBySession.set(sessionId, typeof seed.reasoningEffort === 'string' && seed.reasoningEffort !== '' ? seed.reasoningEffort : undefined);
        const lastIndex = scannedIndex.get(sessionId) ?? -1;
        for (const usage of usageSince(events, lastIndex)) {
            recordUsage(sessionId, {
                turn: usage.turn,
                step: usage.step,
                provider: usage.provider,
                model: usage.model,
                inputTokens: usage.inputTokens,
                outputTokens: usage.outputTokens,
                cacheReadTokens: usage.cacheReadTokens,
                cacheWriteTokens: usage.cacheWriteTokens,
            }, '无记录（插件中途启用或会话恢复）');
        }
        if (events.length === 0 && recentUsage.length > 0) {
            for (const usage of recentUsage.filter((u) => u.sessionId === null || u.sessionId === sessionId)) {
                recordUsage(sessionId, usage, "fallback (no events on payload)");
            }
            for (let i = recentUsage.length - 1; i >= 0; i -= 1) {
                const u = recentUsage[i];
                if (u.sessionId === null || u.sessionId === sessionId) recentUsage.splice(i, 1);
            }
        }
        if (events.length > 0)
            scannedIndex.set(sessionId, events.length - 1);
        // 2) Plan. The ONLY trigger for scheduling is the toggle button being ON
        //    (settings key autoOn). While ON, the manual picker is ignored. While
        //    OFF, everything rides through untouched (native manual selection).
        const selected = seed.reasoningEffort;
        const autoActive = cfg.autoOn === true;
        const echoOfOverride = plan_echoCheck(lastOverride, manualPick, selected, sessionId);
        const plan = autoActive
            ? { mode: 'schedule' }
            : { mode: 'passthrough' };
        let tier = 'high';
        let classifierSource = 'n/a';
        let classifierScore = 0;
        if (plan.mode === 'schedule') {
            let message = latestUserMessage(events);
            if (message === undefined && lastClaimedText !== null &&
                (payload.turn === undefined || lastClaimedTurn === -1 || payload.turn === lastClaimedTurn)) {
                message = { text: lastClaimedText, index: -1 };
            }
            let result = message ? scoreCache.lookup(message.text) : undefined;
            if (result === undefined && message !== undefined) {
                const cooling = scorerBackoff.cooling(message.text);
                result = cfg.mode === 'minimax' && !cooling
                    ? await minimaxClassify(message.text, {
                        apiKey: cfg.minimaxApiKey,
                        baseUrl: cfg.minimaxBaseUrl,
                        model: cfg.minimaxModel,
                        timeoutMs: cfg.scoreTimeoutMs,
                    })
                    : heuristicClassify(message.text, cooling ? 'scorer cooling down after a failure' : undefined);
                if (result.note === undefined)
                    scoreCache.remember(message.text, result);
                else
                    scorerBackoff.markFailed(message.text);
                if (result.note !== undefined) {
                    ctx.logger?.warn?.('[effort-auto-toggle] scorer: %s', result.note);
                }
            }
            tier = result?.tier ?? 'high';
            classifierSource = result?.source ?? 'unknown';
            classifierScore = result?.score ?? 0;
        }
        let effort;
        let reason;
        if (plan.mode === 'schedule') {
            // Session-scoped tool evidence, window-filtered: another session's
            // activity must not contaminate this one, and a call from an hour ago
            // must not either. The size policy (how many rungs a payload buys)
            // belongs to the scheduler, so no separate continuity lift is applied
            // here — that duplication is what used to double count.
            const liveCalls = recentCallsFor(sessionId).calls;
            const calls = liveCalls.length > 0 ? liveCalls : recentToolCalls(events);
            const msgText = (latestUserMessage(events) ?? { text: lastClaimedText, index: -1 }).text;
            const boosted = applySignalBoosts(sessionId, msgText, tier, classifierSource, payload.step === 1 || payload.step === undefined);
            tier = boosted.tier;
            classifierSource = boosted.source;
const decision = scheduleEffort({
                scoredTier: tier,
                recentCalls: calls,
                allowToolUpgrade: cfg.allowToolUpgrade,
                selected: 'auto',
                defaultTier: 'high',
            });
            // The scheduled path can only ever produce low/high/max (never off,
            // never medium); only a manual passthrough may carry `off`, handled
            // by the forced-thinking clamp below.
            if (!decision.manual)
                assertAutoTier(decision.effort, 'dsh-effort-auto-toggle scheduler');
            // 0.2.0: the scheduler speaks SEMANTIC tiers (low/high/max); map
            // them onto the real levels of this model ("high" may land on
            // "highx", "max" on "ultra", a 2-level model collapses, ...).
            effort = decision.manual ? decision.effort : semanticToLadder(decision.effort, ladder);
            if (!decision.manual)
                assertScheduledEffort(effort, ladder, 'dsh-effort-auto-toggle scheduler');
            reason = decision.reason;
        }
        else {
            reason = 'idle (auto button off, manual effort)';
        }
        // 2.5) Host 0.2.2+ (agent.model available): agent/request is READ-ONLY.
        // The loop validates the proposal equals the step's fixed selection,
        // so nothing is rewritten here. Effort changes ride agent.model.select()
        // — the claim-time decision already fired for this turn's first step;
        // here we queue refinements for the NEXT step (tool-continuity bumps,
        // delayed minimax verdicts) and keep the ledger honest about the wire.
        if (modern) {
            const wire = typeof seed.reasoningEffort === "string" && seed.reasoningEffort !== "" ? seed.reasoningEffort : undefined;
            if (plan.mode === "schedule") {
                if (typeof effort === "string" && effort !== wire)
                    modernSelect(agent, effort);
                const turnStep = readTurnStep(events, payload);
                if (turnStep !== undefined) {
                    const claimedFresh = claimedDecision !== null && claimedDecision.turn === turnStep.turn && turnStep.step === 1;
                    const reason = claimedFresh
                        ? claimedDecision.reason
                        : (typeof effort === "string" && effort !== wire
                            ? "select " + effort + " queued for next step (wire " + String(wire ?? "adapter default") + ")"
                            : "scheduled (model.select path)");
                    pending.set(turnStep.key, {
                        tier: claimedFresh ? claimedDecision.tier : guessSemantic(wire, ladder),
                        effort: wire ?? semanticToLadder("high", ladder),
                        reason,
                        classifierSource: claimedFresh ? claimedDecision.classifierSource : classifierSource,
                        classifierScore: claimedFresh ? claimedDecision.classifierScore : classifierScore,
                    });
                    if (pending.size > 128) {
                        const oldest = pending.keys().next().value;
                        if (oldest !== undefined)
                            pending.delete(oldest);
                    }
                }
                const preAuto = lastOverride.autoOn === true
                    ? lastOverride.preAutoEffort
                    : (wire !== undefined && wire !== "off" ? wire : undefined);
                lastOverride = { sessionId, effort: typeof effort === "string" ? effort : undefined, autoOn: true, preAutoEffort: preAuto, ts: Date.now() };
                persistOverrideState(lastOverride);
                ctx.logger?.info?.("[effort-auto-toggle] agent/request(model.select): plan=%s wire=%s desired=%s", plan.mode, String(wire), String(effort));
                return seed;
            }
            // passthrough on a modern host: selections are always provider-valid,
            // so nothing needs sanitising — only disarm-restore and the
            // forced-thinking off clamp, both applied via select() (next step).
            const savedPre = isPickableEffort(lastOverride.preAutoEffort, ladder) ? lastOverride.preAutoEffort : undefined;
            const wasArmed = lastOverride.autoOn === true;
            if (wasArmed) {
                lastOverride = { sessionId: null, effort: undefined, autoOn: false, preAutoEffort: undefined, ts: Date.now() };
                persistOverrideState(lastOverride);
                if (savedPre !== undefined && savedPre !== wire) {
                    modernSelect(agent, savedPre);
                    ctx.logger?.info?.("[effort-auto-toggle] auto disarmed (model.select): restoring pre-auto manual effort %s", savedPre);
                }
            }
            if (!echoOfOverride && wire !== undefined && wire !== "off" && manualPick.effort !== wire)
                manualPick = { sessionId, effort: wire };
            if (wire === "off" && cfg.clampForcedThinkingOff === true) {
                const clamp = clampForModel("off", model, ladder);
                if (clamp.clamped) {
                    modernSelect(agent, clamp.effort);
                    ctx.logger?.warn?.("[effort-auto-toggle] %s is a forced-thinking model; off clamped to %s via model.select", model || "(unknown model)", clamp.effort);
                }
            }
            return seed;
        }
        // 3) Resolve the effort that actually goes on the wire.
        //
        // Invariants — each one is a real provider rejection, not a taste call:
        //   * `auto` must NEVER reach the provider: it is a phantom tier that
        //     only exists while a plugin advertises it (the provider answers
        //     UNSUPPORTED_REASONING_EFFORT). It can still be sitting in the
        //     selection after the toggle went dark, after a plugin reload or a
        //     session resume, so the passthrough path sanitises it as well.
        //   * `off` must not reach a forced-thinking model (GLM-5.3 family):
        //     clamp it to `low`.
        let finalEffort = effort;
        let clamped = false;
        let sanitized = false;
        let restore = false;
        if (plan.mode === 'passthrough') {
            const wire = isPickableEffort(selected, ladder) ? selected : undefined;
            // A genuine manual pick (an echo of our own override is never one).
            if (!echoOfOverride && wire !== undefined && wire !== 'off' && manualPick.effort !== wire)
                manualPick = { sessionId, effort: wire };
            const savedPre = isPickableEffort(lastOverride.preAutoEffort, ladder) ? lastOverride.preAutoEffort : undefined;
            const wasArmed = lastOverride.autoOn === true;
            if (wasArmed) {
                // Disarm edge: forget the override so the next seed is trusted.
                lastOverride = { sessionId: null, effort: undefined, autoOn: false, preAutoEffort: undefined, ts: Date.now() };
                persistOverrideState(lastOverride);
            }
            if (wire !== undefined) {
                if (wasArmed && echoOfOverride && savedPre !== undefined) {
                    // The seed is the echo of our own last auto override: put the
                    // manual effort back instead of keeping the auto pick.
                    finalEffort = savedPre;
                    sanitized = true;
                    restore = true;
                    reason = 'auto disarmed: restoring pre-auto manual effort';
                }
                else {
                    finalEffort = wire;
                }
            }
            else if (selected === undefined || selected === null) {
                finalEffort = undefined; // nothing selected: leave the seed alone
            }
            else {
                // An unsupported value is on the wire (`auto`, `medium`, junk).
                finalEffort = savedPre ?? (isPickableEffort(manualPick.effort, ladder) ? manualPick.effort : undefined) ?? semanticToLadder('high', ladder);
                sanitized = true;
                reason = `unsupported effort ${JSON.stringify(String(selected))} sanitised -> ${finalEffort}`;
                ctx.logger?.warn?.('[effort-auto-toggle] effort "%s" is not accepted by the provider; sending "%s" instead', String(selected), finalEffort);
            }
        }
        if (finalEffort === 'off' && cfg.clampForcedThinkingOff) {
            const clamp = clampForModel(finalEffort, model, ladder);
            if (clamp.clamped) {
                finalEffort = clamp.effort;
                clamped = true;
                sanitized = true;
                reason = `${reason}; off->low clamp (forced-thinking model)`;
            }
        }
        if (clamped)
            ctx.logger?.warn?.('[effort-auto-toggle] %s is a forced-thinking model (GLM-5.3 etc.); off would be rejected, clamped to low', model || '(unknown model)');
        if (plan.mode === 'passthrough') {
            ctx.logger?.info?.('[effort-auto-toggle] agent/request: plan=passthrough selected=%s%s%s', String(selected), sanitized ? ` -> ${finalEffort}` : '', restore ? ' (restored)' : '');
            if (!sanitized)
                return seed; // untouched manual selection
        }
        else {
            ctx.logger?.info?.('[effort-auto-toggle] agent/request: plan=%s selected=%s scored=%s(%s,%d) => effort=%s', plan.mode, String(selected), tier, classifierSource, classifierScore, String(finalEffort));
        }
        // 4) Remember the decision for this step's usage record.
        const turnStep = readTurnStep(events, payload);
        if (turnStep !== undefined) {
            pending.set(turnStep.key, { tier, effort: finalEffort ?? 'high', reason, classifierSource, classifierScore });
            if (pending.size > 128) {
                const oldest = pending.keys().next().value;
                if (oldest !== undefined)
                    pending.delete(oldest);
            }
        }
        if (finalEffort === undefined)
            return seed;
        if (plan.mode === 'schedule') {
            // Arming edge: remember the manual effort that was live before the
            // first auto override, so disarming can put it back.
            const preAuto = lastOverride.autoOn === true
                ? lastOverride.preAutoEffort
                : (isWireEffort(selected) === true && selected !== 'off' ? selected : undefined);
            lastOverride = { sessionId, effort: finalEffort, autoOn: true, preAutoEffort: preAuto, ts: Date.now() };
            persistOverrideState(lastOverride);
        }
        return { ...seed, reasoningEffort: finalEffort };
    }, { prepend: true });
}

let overrideStateDir = null;
function overrideStatePath() {
    return join(overrideStateDir || join(homedir(), ".dsh", "effort-auto-toggle"), "override-state.json");
}
function loadOverrideState() {
    try {
        let text = readFileSync(overrideStatePath(), "utf8");
        if (text.charCodeAt(0) === 0xfeff) text = text.slice(1); // strip BOM
        const raw = JSON.parse(text);
        if (raw && typeof raw === "object" && typeof raw.sessionId !== "undefined") {
            return {
                sessionId: typeof raw.sessionId === "string" ? raw.sessionId : null,
                effort: typeof raw.effort === "string" ? raw.effort : undefined,
                autoOn: raw.autoOn === true,
                preAutoEffort: typeof raw.preAutoEffort === "string" ? raw.preAutoEffort : undefined,
                ts: typeof raw.ts === "number" ? raw.ts : 0,
            };
        }
    } catch {}
    return { sessionId: null, effort: undefined, autoOn: false, preAutoEffort: undefined, ts: 0 };
}
function persistOverrideState(state) {
    try {
        mkdirSync(dirname(overrideStatePath()), { recursive: true });
        writeFileSync(overrideStatePath(), JSON.stringify(state));
    } catch {}
}
// Host 0.2.2+ moved effort from the agent/request waterfall (whose result is
// now validated against the step's fixed selection) onto the model selection
// (agent.model.select). Detect that API per event payload: every agent event
// payload is fused with the agent instance by the host event bus.
function hostModern(agent) {
    return typeof agent === "object" && agent !== null
        && typeof agent.model === "object" && agent.model !== null
        && typeof agent.model.select === "function"
        && typeof agent.model.current === "function";
}
/** Apply an effort (or an effort-less route) via the host model selection. */
function modernSelect(agent, effort) {
    try {
        const sel = agent.model.current();
        if (!sel || typeof sel.provider !== "string" || !sel.provider || typeof sel.model !== "string" || !sel.model)
            return false;
        agent.model.select({
            provider: sel.provider,
            model: sel.model,
            ...(effort === undefined ? {} : { reasoningEffort: effort }),
        });
        return true;
    } catch {
        return false;
    }
}
/**
 * Read the session's event log across host generations.
 *
 * dsh 0.2.2-rc.3 dropped the `session.events` getter, so probing only that
 * property silently yields an empty log (every usage row then records
 * `unknown`). Read the modern snapshot reader first — deprecated but
 * functional, and O(1) per step because the host caches the frozen array
 * until the next append — then fall back through the older shapes.
 */
function readEvents(agent) {
    if (typeof agent !== 'object' || agent === null)
        return [];
    const session = agent.session;
    if (typeof session !== 'object' || session === null)
        return [];
    try {
        if (typeof session.snapshotEvents === 'function') {
            const snapshot = session.snapshotEvents();
            if (Array.isArray(snapshot))
                return snapshot;
        }
    }
    catch { }
    try {
        if (typeof session.ownEvents === 'function') {
            const own = session.ownEvents();
            if (Array.isArray(own))
                return own;
        }
    }
    catch { }
    try {
        if (typeof session.eventAt === 'function' && typeof session.seq === 'number') {
            const events = [];
            for (let index = 0; index < session.seq; index += 1) {
                const event = session.eventAt(index);
                if (event !== undefined)
                    events.push(event);
            }
            if (events.length > 0)
                return events;
        }
    }
    catch { }
    const legacy = session.events;
    return Array.isArray(legacy) ? legacy : [];
}
/** Session id of a broadcast `session/event` subject (null when unattributable). */
function sessionIdOfEvent(session) {
    if (typeof session !== "object" || session === null)
        return null;
    const id = session.id ?? session.sessionId;
    return typeof id === "string" && id.length > 0 ? id : null;
}
function plan_echoCheck(lastOverride, manualPick, selected, sessionId) {
    if (typeof selected !== "string") return false;
    if (selected === "off" || selected === "auto") return false;
    if (isWireEffort(selected) !== true) return false;
    if (lastOverride.sessionId !== sessionId) return false;
    if (lastOverride.effort !== selected) return false;
    if (manualPick.sessionId === sessionId && manualPick.effort === selected) return false;
    if (Date.now() - lastOverride.ts > 30 * 60 * 1000) return false;
    return true;
}
function readTurnStep(events, payload) {
    const fromPayload = readNumbers(payload.turn) && readNumbers(payload.step);
    if (fromPayload) {
        return { key: `${payload.turn}:${payload.step}`, turn: payload.turn, step: payload.step };
    }
    for (let index = events.length - 1; index >= 0; index -= 1) {
        const event = events[index];
        if (typeof event !== 'object' || event === null)
            continue;
        if (event.type !== 'step/start')
            continue;
        const data = event.data;
        if (typeof data !== 'object' || data === null)
            continue;
        const turn = data.turn;
        const step = data.step;
        if (typeof turn === 'number' && typeof step === 'number') {
            return { key: `${turn}:${step}`, turn, step };
        }
    }
    return undefined;
}
function readNumbers(...values) {
    return values.every(value => typeof value === 'number');
}
export async function reportFor(sessionId, dir) {
    const { buildReport, renderReport } = await import("./ledger.js");
    const ledger = new Ledger(dir || defaultLedgerDir());
    overrideStateDir = dir || defaultLedgerDir();
    const records = await ledger.read(sessionId);
    return renderReport(buildReport(records));
}
